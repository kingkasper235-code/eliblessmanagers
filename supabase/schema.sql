create extension if not exists "pgcrypto";

create table if not exists public.admin_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'admin' check (role in ('admin', 'manager')),
  created_at timestamptz not null default now()
);

create table if not exists public.owners (
  id bigint generated by default as identity primary key,
  slot_number smallint not null unique check (slot_number in (1, 2)),
  name text not null default '',
  title text not null default '',
  bio text not null default '',
  photo_url text not null default '',
  is_active boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint active_owner_requires_name check (not is_active or length(trim(name)) > 0)
);

create table if not exists public.google_business_settings (
  id integer primary key default 1 check (id = 1),
  listing_url text not null default 'https://maps.app.goo.gl/4aRcQcEtzcHtt8878',
  place_id text,
  widget_enabled boolean not null default true,
  live_data_enabled boolean not null default false,
  connection_status text not null default 'not_configured'
    check (connection_status in ('not_configured', 'connected', 'error')),
  checked_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint google_business_place_id_format check (
    place_id is null or (
      length(place_id) between 1 and 255
      and place_id ~ '^[A-Za-z0-9_-]+$'
    )
  )
);

insert into public.google_business_settings (id)
values (1)
on conflict (id) do nothing;

create table if not exists public.properties (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text not null unique,
  description text,
  price numeric(14,2) not null default 0,
  currency text not null default 'NGN',
  property_type text not null,
  listing_type text not null check (listing_type in ('sale', 'rent')),
  location text,
  address text,
  city text,
  state text,
  bedrooms integer not null default 0,
  bathrooms integer not null default 0,
  toilets integer not null default 0,
  property_size integer not null default 0,
  year_built integer,
  status text not null default 'available' check (status in ('available', 'pending', 'sold', 'leased', 'rented', 'unavailable')),
  featured boolean not null default false,
  published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.property_images (
  id bigint generated by default as identity primary key,
  property_id bigint not null references public.properties(id) on delete cascade,
  image_url text not null,
  display_order integer not null default 0,
  is_primary boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.property_videos (
  id bigint generated by default as identity primary key,
  property_id bigint not null references public.properties(id) on delete cascade,
  storage_path text unique,
  source_type text not null check (source_type in ('upload', 'youtube')),
  video_url text,
  title text not null default '',
  display_order integer not null default 0 check (display_order >= 0),
  upload_status text not null default 'pending'
    check (upload_status in ('pending', 'ready', 'failed')),
  replaces_video_id bigint references public.property_videos(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint property_videos_source_fields check (
    (
      source_type = 'upload'
      and storage_path is not null
      and storage_path ~ ('^properties/' || property_id::text || '/[^/]+[.]mp4$')
      and video_url is null
    )
    or
    (source_type = 'youtube' and storage_path is null and video_url is not null and upload_status = 'ready')
  )
);

create table if not exists public.property_amenities (
  id bigint generated by default as identity primary key,
  property_id bigint not null references public.properties(id) on delete cascade,
  amenity text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.enquiries (
  id bigint generated by default as identity primary key,
  property_id bigint references public.properties(id) on delete set null,
  name text not null,
  email text not null,
  phone text not null,
  message text not null,
  status text not null default 'New' check (status in ('New', 'Contacted', 'Closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

