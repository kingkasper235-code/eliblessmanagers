create policy "Authorized users can read property videos"
on storage.objects
for select
using (
  bucket_id = 'property-videos'
  and (
    public.is_admin()
    or exists (
      select 1
      from public.property_videos pv
      join public.properties p on p.id = pv.property_id
      where pv.storage_path = storage.objects.name
        and pv.property_id::text = (storage.foldername(storage.objects.name))[2]
        and pv.source_type = 'upload'
        and pv.upload_status = 'ready'
        and p.published = true
        and p.status in ('available', 'pending')
    )
  )
);

