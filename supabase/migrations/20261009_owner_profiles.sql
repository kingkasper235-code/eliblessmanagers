create table if not exists public.owners (
  id bigint generated by default as identity primary key,
  slot_number smallint not null unique check (slot_number in (1, 2)),
  name text not null default '',
  title text not null default '',
  bio text not null default '',
  photo_url text not null default '',
  is_active boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint active_owner_requires_name check (not is_active or length(trim(name)) > 0)
);

create index if not exists idx_owners_active_slot
  on public.owners(is_active, slot_number);

drop trigger if exists owners_set_updated_at on public.owners;
create trigger owners_set_updated_at
before update on public.owners
for each row
execute function public.update_updated_at();

alter table public.owners enable row level security;

drop policy if exists "Public can view active owners" on public.owners;
create policy "Public can view active owners"
on public.owners
for select
using (is_active = true);

drop policy if exists "Admins can manage owner profiles" on public.owners;
create policy "Admins can manage owner profiles"
on public.owners
for all
using (public.is_admin())
with check (public.is_admin());

grant select on public.owners to anon, authenticated;
grant insert, update, delete on public.owners to authenticated;
grant usage, select on sequence public.owners_id_seq to authenticated;

drop policy if exists "Admins can upload property images" on storage.objects;
create policy "Admins can upload property images"
on storage.objects
for insert
with check (
  bucket_id = 'property-images'
  and public.is_admin()
  and (storage.foldername(name))[1] in ('properties', 'owners')
);

drop policy if exists "Admins can update property images" on storage.objects;
create policy "Admins can update property images"
on storage.objects
for update
using (
  bucket_id = 'property-images'
  and public.is_admin()
)
with check (
  bucket_id = 'property-images'
  and public.is_admin()
  and (storage.foldername(name))[1] in ('properties', 'owners')
);

drop policy if exists "Public can view owner profile images in storage" on storage.objects;
create policy "Public can view owner profile images in storage"
on storage.objects
for select
using (
  bucket_id = 'property-images'
  and (storage.foldername(name))[1] = 'owners'
);
