create table if not exists public.property_videos (
  id bigint generated by default as identity primary key,
  property_id bigint not null references public.properties(id) on delete cascade,
  storage_path text unique,
  source_type text not null check (source_type in ('upload', 'youtube')),
  video_url text,
  title text not null default '',
  display_order integer not null default 0 check (display_order >= 0),
  upload_status text not null default 'pending'
    check (upload_status in ('pending', 'ready', 'failed')),
  replaces_video_id bigint references public.property_videos(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint property_videos_source_fields check (
    (
      source_type = 'upload'
      and storage_path is not null
      and storage_path ~ ('^properties/' || property_id::text || '/[^/]+[.]mp4$')
      and video_url is null
    )
    or
    (source_type = 'youtube' and storage_path is null and video_url is not null and upload_status = 'ready')
  )
);

create index if not exists idx_property_videos_property_order
  on public.property_videos(property_id, display_order, created_at);

alter table public.property_videos enable row level security;

drop policy if exists "Admins can manage property videos" on public.property_videos;
create policy "Admins can manage property videos"
on public.property_videos
for all
using (public.is_admin())
with check (public.is_admin());

drop policy if exists "Public can read published property videos" on public.property_videos;
create policy "Public can read published property videos"
on public.property_videos
for select
using (
  upload_status = 'ready'
  and exists (
    select 1
    from public.properties p
    where p.id = property_id
      and p.published = true
      and p.status in ('available', 'pending')
  )
);

revoke all on public.property_videos from public, anon, authenticated;
grant select on public.property_videos to anon, authenticated;
grant insert, update, delete on public.property_videos to authenticated;
revoke all on sequence public.property_videos_id_seq from public, anon, authenticated;
grant usage, select on sequence public.property_videos_id_seq to authenticated;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('property-videos', 'property-videos', false, 52428800, array['video/mp4'])
on conflict (id) do update
set
  name = excluded.name,
  public = false,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Admins can upload property videos" on storage.objects;
create policy "Admins can upload property videos"
on storage.objects
for insert
with check (
  bucket_id = 'property-videos'
  and public.is_admin()
  and lower(name) ~ '^properties/[0-9]+/[^/]+[.]mp4$'
  and exists (
    select 1
    from public.property_videos pv
    where pv.storage_path = storage.objects.name
      and pv.property_id::text = (storage.foldername(name))[2]
      and pv.source_type = 'upload'
      and pv.upload_status in ('pending', 'failed')
  )
);

drop policy if exists "Admins can update property videos" on storage.objects;
create policy "Admins can update property videos"
on storage.objects
